export function foldPlace(value = "") {
  return value
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/ς/g, "σ")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

export const municipalities = rows.map(([id, el, en, genitive]) => ({
  id,
  el,
  en,
  searchText: foldPlace([el, en, genitive].join(" ")),
}));
const byId = new Map(municipalities.map((place) => [place.id, place]));
const byName = new Map();
for (const [id, el, en, genitive] of rows) {
  for (const name of [
    id,
    el,
    en,
    genitive,
    "Δήμος " + genitive,
    ...(oldNames[id] || []),
  ]) {
    const key = foldPlace(name);
    // Two municipalities share the official name Δήμος Ηρακλείου.
    byName.set(key, byName.has(key) && byName.get(key) !== id ? "" : id);
  }
}
export function municipalityById(id) {
  return byId.get(id);
}
export function legacyMunicipalityId(...values) {
  for (const value of values) {
    const match = typeof value === "string" && byName.get(foldPlace(value));
    if (match) return match;
  }
  return "";
}
